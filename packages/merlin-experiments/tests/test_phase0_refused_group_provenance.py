"""A generated but refused qualifying group is neither authored nor a phase member."""

import yaml

from merlin_experiments.phase0.provenance import update_provenance_manifest


def test_refused_generated_group_is_diagnostic_provenance_only(tmp_path) -> None:
    root = tmp_path / "capsules"
    model = root / "model" / "SY_source_fixture"
    group = root / "layers" / "G_residual_fixture"
    for directory in (model, group):
        directory.mkdir(parents=True)
        (directory / "capsule.yaml").write_text("name: fixture\n", encoding="utf-8")

    update_provenance_manifest(
        [model], cap_root=root, target="synthetic", refused_generated=[group], performance_record={}
    )
    manifest = yaml.safe_load((root / "MANIFEST.yaml").read_text(encoding="utf-8"))
    assert manifest["generated"] == ["model/SY_source_fixture"]
    assert manifest["refused_generated"] == ["layers/G_residual_fixture"]
    assert manifest["hand_authored"] == []
    assert manifest["phase_corpora"]["synthetic"]["phase1"]["generated_members"] == [
        "model/SY_source_fixture"
    ]
    assert all(
        "layers/G_residual_fixture" not in selection["generated_members"]
        for role, selection in manifest["phase_corpora"]["synthetic"].items()
        if role in {"phase1", "phase2", "diagnostic"}
    )

    # A later reviewed run may admit the same generated bytes; the diagnostic
    # classification then disappears instead of persisting as a stale refusal.
    update_provenance_manifest([model, group], cap_root=root, target="synthetic", performance_record={})
    promoted = yaml.safe_load((root / "MANIFEST.yaml").read_text(encoding="utf-8"))
    assert promoted["refused_generated"] == []
    assert "layers/G_residual_fixture" in promoted["phase_corpora"]["synthetic"]["phase1"]["generated_members"]
